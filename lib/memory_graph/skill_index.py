"""
skill_index.py — Index Hermes skills into the fleet soul graph.

Each skill becomes a soul_nodes row (kind=skill-ref, visibility=fleet).
related_skills frontmatter links become soul_edges.
Full-text search (search_vec tsvector) is auto-generated by Postgres.
Vector embedding slot (vector(1536)) is populated when available.

Usage:
    python3 skill_index.py --index          # index/refresh all local skills
    python3 skill_index.py --search "rag"   # full-text search skills (all agents)
    python3 skill_index.py --agent bullwinkle --search "git"  # one agent only
    python3 skill_index.py --stats          # fleet skill stats

Design:
    node id  = sha256("skill:<agent>:<name>")[:16]  — deterministic, stable
    content  = "SKILL:<name>\\n<description>\\n\\nTags: ...\\nRelated: ..."
    tags     = ["skill", "skill-ref", ...skill's own tags...]
    metadata = {"skill_name": ..., "skill_path": ..., "agent": ..., "version": ...}
"""

import hashlib
import json
import os
import re
import sys
from pathlib import Path
from datetime import datetime, timezone

# ── Resolve imports whether run directly or as module ─────────────────────────
_HERE = Path(__file__).parent
sys.path.insert(0, str(_HERE))
import pg_memory as pg

AGENT_ID = os.environ.get("FLEET_AGENT_ID", "natasha")
SKILLS_ROOT = Path.home() / ".hermes/skills"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _skill_node_id(agent: str, skill_name: str) -> str:
    key = f"skill:{agent}:{skill_name}"
    return hashlib.sha256(key.encode()).hexdigest()[:16]


def _parse_skill(skill_md: Path) -> dict | None:
    """Parse a SKILL.md file into a structured dict."""
    try:
        text = skill_md.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return None

    name = skill_md.parent.name
    description = ""
    tags = []
    related = []
    version = ""
    body = text

    if text.startswith("---"):
        try:
            end = text.index("---", 3)
            fm = text[3:end].strip()
            body = text[end + 3 :].strip()
            for line in fm.splitlines():
                stripped = line.strip()
                if stripped.startswith("name:"):
                    name = stripped.split(":", 1)[1].strip()
                elif stripped.startswith("description:"):
                    description = stripped.split(":", 1)[1].strip().strip("\"'")
                elif stripped.startswith("version:"):
                    version = stripped.split(":", 1)[1].strip()
                elif "tags:" in stripped and "[" in stripped:
                    raw = stripped.split("[", 1)[1].rstrip("]")
                    tags = [t.strip().strip("'\"") for t in raw.split(",") if t.strip()]
                elif "related_skills:" in stripped and "[" in stripped:
                    raw = stripped.split("[", 1)[1].rstrip("]")
                    related = [t.strip().strip("'\"") for t in raw.split(",") if t.strip()]
        except (ValueError, IndexError):
            pass

    # Build the content that will be indexed and searched
    # Include description + first 1500 chars of body for FTS richness
    body_excerpt = body[:1500].strip()
    content = f"SKILL:{name}\n{description}\n\nTags: {', '.join(tags)}\nRelated: {', '.join(related)}\n\n{body_excerpt}"

    return {
        "name": name,
        "description": description,
        "tags": tags,
        "related": [r for r in related if r],
        "version": version,
        "path": str(skill_md),
        "content": content,
    }


PERSONAL_HEADERS = {"pitfall", "lesson", "preference", "warning", "known issue", "gotcha", "my "}
MACHINE_HEADERS = {
    "install",
    "setup",
    "config",
    "environment",
    "path",
    "endpoint",
    "host",
    "machine",
    "platform",
}


def _section_scope(header_line: str) -> str:
    """Classify a section header as 'general', 'machine', or 'personal'."""
    h = re.sub(r"^#+\s*", "", header_line).lower().strip()
    if any(h.startswith(p) for p in PERSONAL_HEADERS):
        return "personal"
    if any(h.startswith(p) for p in MACHINE_HEADERS):
        return "machine"
    return "general"


def _split_by_scope(body: str) -> dict[str, list[str]]:
    """Split skill body into {general, machine, personal} section buckets."""
    buckets: dict[str, list[str]] = {"general": [], "machine": [], "personal": []}
    current_scope = "general"
    current_lines: list[str] = []
    for line in body.splitlines():
        if re.match(r"^#{1,3} ", line):
            if current_lines:
                buckets[current_scope].append("\n".join(current_lines).strip())
            current_scope = _section_scope(line)
            current_lines = [line]
        else:
            current_lines.append(line)
    if current_lines:
        buckets[current_scope].append("\n".join(current_lines).strip())
    return buckets


def annotate_skill(skill_name: str, scope: str, content: str, agent: str = AGENT_ID) -> str | None:
    """
    Write a locality-scoped annotation node for a skill and link it.

    scope: 'personal' — your experience/pitfalls/preferences (visibility:fleet,
                         tagged agent:<you> so peers know it's your experience)
           'machine'  — machine-local config/paths (visibility:personal,
                         stays on this machine only)

    Returns the annotation node_id, or None on failure.
    """
    skill_node_id = _skill_node_id(agent, skill_name)
    ann_id = hashlib.sha256(
        f"skill-annotation:{agent}:{skill_name}:{scope}:{content[:64]}".encode()
    ).hexdigest()[:16]

    if scope == "personal":
        tags = [
            "skill-annotation",
            f"scope:personal",
            f"agent:{agent}",
            "visibility:fleet",
            "skill",
        ]
    else:  # machine
        tags = [
            "skill-annotation",
            f"scope:machine",
            f"agent:{agent}",
            f"platform:{sys.platform}",
            "visibility:personal",
            "skill",
        ]

    # Write to local SQLite + PG (via dual-write in pg_memory)
    ok = pg.upsert_node(
        node_id=ann_id,
        content=f"SKILL-ANNOTATION:{skill_name} [{scope}]\nagent:{agent}\n\n{content}",
        kind="memory",
        tags=tags,
        pinned=False,
        score=1.0,
        created_at=_now(),
    )
    if ok:
        # Edge: annotation ──refines──▶ skill-ref
        pg.upsert_edge(ann_id, skill_node_id, relation="refines")
    return ann_id if ok else None


def index_skills(
    agent: str = AGENT_ID, skills_root: Path = SKILLS_ROOT, verbose: bool = True
) -> dict:
    """
    Walk skills_root, upsert every skill as a soul_nodes skill-ref.
    Returns {"indexed": N, "edges": N, "errors": N}.
    """
    if not skills_root.exists():
        return {"indexed": 0, "edges": 0, "errors": 0, "error": f"{skills_root} not found"}

    skills = []
    for skill_md in sorted(skills_root.rglob("SKILL.md")):
        parsed = _parse_skill(skill_md)
        if parsed:
            skills.append(parsed)

    indexed = edges = errors = 0
    name_to_id: dict[str, str] = {}

    # Phase 1: upsert all skill nodes
    for s in skills:
        node_id = _skill_node_id(agent, s["name"])
        name_to_id[s["name"]] = node_id

        node_tags = list({"skill", "skill-ref"} | set(s["tags"]))
        node_tags.append(f"visibility:fleet")
        node_tags.append(f"agent:{agent}")

        # Only index the GENERAL sections in the main skill-ref node
        # (machine/personal sections go into separate annotation nodes)
        try:
            skill_path = Path(s["path"])
            raw = skill_path.read_text(encoding="utf-8", errors="replace")
            if raw.startswith("---"):
                end_fm = raw.index("---", 3)
                body = raw[end_fm + 3 :].strip()
            else:
                body = raw
            buckets = _split_by_scope(body)
            general_text = "\n\n".join(buckets["general"])[:1500]
        except Exception:
            buckets = {"general": [], "machine": [], "personal": []}
            general_text = s["content"]

        general_content = (
            f"SKILL:{s['name']}\n{s['description']}\n\n"
            f"Tags: {', '.join(s['tags'])}\nRelated: {', '.join(s['related'])}\n\n"
            f"{general_text}"
        )

        ok = pg.upsert_node(
            node_id=node_id,
            content=general_content,
            kind="skill-ref",
            tags=node_tags,
            pinned=False,
            score=1.0,
            created_at=_now(),
        )
        if ok:
            indexed += 1
            if verbose:
                print(f"  ✓ {s['name']}")
        else:
            errors += 1
            if verbose:
                print(f"  ✗ {s['name']} (pg write failed)")

        # Phase 1b: extract machine/personal sections as annotation nodes
        try:
            if buckets["personal"]:
                personal_text = "\n\n".join(buckets["personal"])
                annotate_skill(s["name"], "personal", personal_text, agent)
            if buckets["machine"]:
                machine_text = "\n\n".join(buckets["machine"])
                annotate_skill(s["name"], "machine", machine_text, agent)
        except Exception:
            pass

    # Phase 2: wire related_skills edges
    for s in skills:
        from_id = name_to_id.get(s["name"])
        if not from_id:
            continue
        for rel_name in s["related"]:
            to_id = name_to_id.get(rel_name)
            if not to_id:
                # Peer's skill — look up by deterministic id (may not exist yet)
                to_id = _skill_node_id(agent, rel_name)
            ok = pg.upsert_edge(from_id, to_id, relation="related-to")
            if ok:
                edges += 1

    return {"indexed": indexed, "edges": edges, "errors": errors}


def search_skills(query: str, limit: int = 8, agent_filter: str | None = None) -> list:
    """
    Full-text search skills across the fleet.
    Returns list of {name, agent, description, tags, score, related_names}.
    """
    # Pull from pg with skill tag filter
    # fleet_search uses FTS; we post-filter for skill-ref nodes
    raw = pg.fleet_search(query, limit=limit * 3, agent_filter=agent_filter or "")
    results = []
    for r in raw:
        if "skill" not in (r.get("tags") or []):
            continue
        # Parse name back from content
        first_line = r["content"].split("\n", 1)[0]
        skill_name = first_line.replace("SKILL:", "").strip()
        # Pull description (second line)
        lines = r["content"].split("\n")
        desc = lines[1].strip() if len(lines) > 1 else ""
        # Pull related from content
        related_names = []
        for line in lines:
            if line.startswith("Related:"):
                related_names = [x.strip() for x in line.split(":", 1)[1].split(",") if x.strip()]
        results.append(
            {
                "name": skill_name,
                "agent": r["agent"],
                "description": desc,
                "tags": r.get("tags", []),
                "score": r["score"],
                "related": related_names,
                "node_id": r["id"],
            }
        )
        if len(results) >= limit:
            break
    return results


def fleet_skill_stats() -> dict:
    """How many skills each agent has indexed."""
    try:
        conn = pg._get_conn()
        cur = conn.cursor()
        cur.execute("""
            SELECT agent, COUNT(*) as skills
            FROM soul_nodes
            WHERE 'skill' = ANY(tags)
            GROUP BY agent ORDER BY skills DESC
        """)
        rows = cur.fetchall()
        return {r[0]: r[1] for r in rows}
    except Exception as e:
        return {"error": str(e)}


def get_skill(name: str, agent: str | None = None) -> dict | None:
    """Fetch a specific skill node with its related skills."""
    try:
        conn = pg._get_conn()
        cur = conn.cursor()
        sql = """
            SELECT id, content, agent, score, tags
            FROM soul_nodes
            WHERE content LIKE %s AND 'skill' = ANY(tags)
        """
        params = [f"SKILL:{name}\n%"]
        if agent:
            sql += " AND agent = %s"
            params.append(agent)
        sql += " LIMIT 1"
        cur.execute(sql, params)
        row = cur.fetchone()
        if not row:
            return None
        node_id, content, ag, score, tags = row

        # Get related skills via edges
        cur.execute(
            """
            SELECT n.content, n.agent
            FROM soul_edges e JOIN soul_nodes n ON n.id = e.child_id
            WHERE e.parent_id = %s AND 'skill-ref' = ANY(n.tags)
            UNION
            SELECT n.content, n.agent
            FROM soul_edges e JOIN soul_nodes n ON n.id = e.parent_id
            WHERE e.child_id = %s AND 'skill-ref' = ANY(n.tags)
        """,
            (node_id, node_id),
        )
        related_rows = cur.fetchall()
        related = [r[0].split("\n", 1)[0].replace("SKILL:", "").strip() for r in related_rows]

        return {
            "name": name,
            "agent": ag,
            "score": score,
            "tags": tags,
            "content": content,
            "related": related,
            "node_id": node_id,
        }
    except Exception as e:
        return {"error": str(e)}


