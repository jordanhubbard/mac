if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--index", action="store_true", help="Index all local skills into fleet PG")
    ap.add_argument("--search", metavar="QUERY", help="Full-text search skills")
    ap.add_argument("--get", metavar="NAME", help="Fetch one skill by name")
    ap.add_argument("--stats", action="store_true", help="Fleet skill stats")
    ap.add_argument("--agent", default=None, help="Filter by agent (search/stats)")
    ap.add_argument("--limit", type=int, default=8, help="Result limit for search")
    args = ap.parse_args()

    pg.set_agent(os.environ.get("FLEET_AGENT_ID", "natasha"))

    if args.index:
        print(f"Indexing skills from {SKILLS_ROOT} as agent '{AGENT_ID}'…")
        result = index_skills(verbose=True)
        print(
            f"\nDone: {result['indexed']} indexed, {result['edges']} edges, {result['errors']} errors"
        )

    elif args.search:
        results = search_skills(args.search, limit=args.limit, agent_filter=args.agent)
        if not results:
            print(f"No skills found for: {args.search!r}")
        for r in results:
            print(f"\n[{r['agent']}] {r['name']}")
            print(f"  {r['description']}")
            if r["related"]:
                print(f"  → related: {', '.join(r['related'])}")

    elif args.get:
        skill = get_skill(args.get, agent=args.agent)
        if not skill:
            print(f"Skill not found: {args.get!r}")
        elif "error" in skill:
            print(f"Error: {skill['error']}")
        else:
            print(f"[{skill['agent']}] {skill['name']}  (score={skill['score']:.2f})")
            print(f"Related: {', '.join(skill['related']) or 'none'}")
            print()
            # Print the body portion only
            body_start = skill["content"].find("\n\n", skill["content"].find("Related:"))
            if body_start > 0:
                print(skill["content"][body_start:].strip()[:2000])

    elif args.stats:
        stats = fleet_skill_stats()
        print("Fleet skill counts:")
        for agent, count in stats.items():
            print(f"  {agent}: {count} skills")

    else:
        ap.print_help()
